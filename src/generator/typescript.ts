/**
 * Generates one module per bounded context, plus a runtime and an index in every directory written to.
 * `dirs` places contexts in directories (`/`-separated, relative to the output directory; default: the output
 * directory itself); each index re-exports only the contexts in its directory. With `tests`, also the contract tests
 * (ADR 0020) into `tests.dir`. Requires a model without errors.
 */
export function generateTypeScript(model: DomainModel, dirs: Readonly<Record<string, string>> = {}, tests?: TestsOptions): GeneratedFile[] {
    const dirOf = (ctx: string): string => posix.normalize(dirs[ctx] || '.');
    const files: GeneratedFile[] = [];
    for (const dir of [...new Set(model.contexts.map(dirOf))]) {
        const contexts = model.contexts.filter((c) => dirOf(c) === dir);
        files.push({ path: posix.join(dir, '_runtime.ts'), content: RUNTIME });
        for (const ctx of contexts) {
            files.push({ path: posix.join(dir, `${ctx}.ts`), content: new ContextEmitter(model, ctx, (other) => moduleSpecifier(dir, dirOf(other), other)).emit() });
        }
        const index = [HEADER, `export * from './_runtime.js';`, ...contexts.map((c) => `export * as ${c} from './${c}.js';`), ''].join('\n');
        files.push({ path: posix.join(dir, 'index.ts'), content: index });
    }
    if (tests) files.push(...generateTests(model, HEADER, { ...tests, dir: posix.normalize(tests.dir) }, (from, ctx) => moduleSpecifier(from, dirOf(ctx), ctx)));
    return files;
}

/** Import specifier of the module of `ctx` in directory `to`, from a module in directory `from`. */
function moduleSpecifier(from: string, to: string, ctx: string): string {
    const rel = posix.relative(from, to);
    if (rel === '') return `./${ctx}.js`;
    return `${rel === '..' || rel.startsWith('../') ? '' : './'}${rel}/${ctx}.js`;
}

/** Text that is safe inside a block comment. */
/** JavaScript line terminators: any of them ends a `//` comment. */
const LINE_TERMINATORS = /\r\n|[\n\r\u2028\u2029]/g;

/** Text that is safe inside a block comment (line breaks normalized to `\n`, `*\/` defused). */
const comment = (s: string): string => s.replace(LINE_TERMINATORS, '\n').replace(/\*\//g, '* /');

/** Text that is safe inside a `//` line comment or on one line of a block comment. */
const oneLine = (s: string): string => comment(s).replace(/\n+/g, ' ');

/** Japanese name and description lines of a declaration. */
const describedLines = (d: Described): string[] => [d.label, d.doc].filter((x): x is string => !!x);

/** JSDoc line of an event declared `persistent`. */
const PERSISTENT_LINE = '@persistent Persisted: storing this event is part of its contract.';

/** JSDoc lines of invariants; one declared without an expression says so. */
const invariantLines = (invs: InvariantModel[]): string[] =>
    invs.map((i) => `@invariant ${i.name}${i.label ? ` (${i.label})` : ''}: ${i.source ?? 'not expressed in the DSL'}`);

/**
 * JSDoc line pointing to the DSL declaration a generated declaration comes from, as `dt check` prints it (relative to
 * the config root, `/`-separated), e.g. `@see sales/order.dt:41`.
 */
const seeLine = (loc: Location): string => `@see ${loc.file.replace(/\\/g, '/')}:${loc.line}`;

/** JSDoc lines of a command's requirements; one declared without an expression says so. */
const requirementLines = (reqs: RequirementModel[], error: (qname: string) => string): string[] =>
    reqs.map((r) => `@requires ${r.name}${r.label ? ` (${r.label})` : ''} else ${error(r.error)}: ${r.source ?? 'not expressed in the DSL'}`);

const unique = (names: string[]): string[] => [...new Set(names)];

/** An outcome of a command: the key of its success value (the target state), its first property and the events. */
interface Outcome {
    key: string;
    /** `aggregate: …` in the contract, `set: …` in the decision. */
    first: string;
    emits: EmitModel[];
}

/** How often an `emits` entry emits its event, in words; `unchecked` when the types do not enforce the bounds. */
function times(e: EmitModel): { words: string; unchecked: boolean } {
    const { lower, upper } = e;
    if (lower === 1 && upper === 1) return { words: 'exactly once', unchecked: false };
    if (lower === 0 && upper === 1) return { words: 'at most once', unchecked: false };
    if (lower === 0 && upper === undefined) return { words: 'zero or more', unchecked: false };
    if (lower === 1 && upper === undefined) return { words: 'one or more', unchecked: false };
    if (upper === undefined) return { words: `${lower} or more`, unchecked: true };
    return { words: lower === upper ? `exactly ${lower} times` : `between ${lower} and ${upper}`, unchecked: true };
}

/** `A`, `A or B`, `A, B or C`. */
const or = (names: string[]): string => (names.length < 2 ? names.join('') : `${names.slice(0, -1).join(', ')} or ${names[names.length - 1]}`);

/** When an `emits` entry applies, in words. */
function condition(w: OutcomePatternModel | undefined): string {
    if (!w || (w.from.length === 0 && w.to.length === 0)) return 'when the command succeeds';
    if (w.to.length === 0) return `when it comes from ${or(w.from)}`;
    if (w.from.length === 0) return `when it ends in ${or(w.to)}`;
    return `when it comes from ${or(w.from)} and ends in ${or(w.to)}`;
}

class ContextEmitter {
    private readonly imports = new Set<string>();
    /** Contexts whose module is imported as a value (its generated checks are called), not only for types. */
    private readonly valueImports = new Set<string>();
    private readonly out: string[] = [];
    private readonly checks: CheckWriter;

    constructor(
        private readonly model: DomainModel,
        private readonly ctx: string,
        /** Import specifier of another context's module. */
        private readonly moduleOf: (ctx: string) => string,
    ) {
        this.checks = new CheckWriter({
            model,
            ctx,
            typeRef: (qname) => this.ref(qname),
            valueRef: (qname, name) => {
                const ctx = qname.slice(0, qname.indexOf('.'));
                if (ctx === this.ctx) return name;
                this.imports.add(ctx);
                this.valueImports.add(ctx);
                return `${ctx}.${name}`;
            },
            fieldType: (f) => this.fieldType(f),
            jsdoc: (lines, loc) => {
                const start = this.out.length;
                this.jsdoc([...lines, seeLine(loc)]);
                return this.out.splice(start);
            },
        });
    }

    /** Lines of generated checks, after a blank line (nothing when there are none). */
    private push(lines: string[]): void {
        if (lines.length) this.out.push('', ...lines);
    }

    emit(): string {
        for (const el of elementsIn(this.model, this.ctx)) {
            switch (el.kind) {
                case 'id':
                case 'primitive':
                    this.primitive(el);
                    break;
                case 'enum':
                    this.jsdoc([...describedLines(el), seeLine(el.location)]);
                    if (!el.values?.length) {
                        this.line(`export type ${el.name} = never;`);
                    } else if (el.valueLabels) {
                        this.line(`export type ${el.name} =`);
                        el.values.forEach((v, i) => {
                            const label = el.valueLabels?.[v];
                            this.line(`    | '${v}'${i === el.values!.length - 1 ? ';' : ''}${label ? ` // ${oneLine(label)}` : ''}`);
                        });
                    } else {
                        this.line(`export type ${el.name} = ${el.values.map((v) => `'${v}'`).join(' | ')};`);
                    }
                    break;
                case 'valueObject':
                case 'entity':
                    this.jsdoc([...describedLines(el), ...invariantLines(el.invariants), seeLine(el.location)]);
                    this.iface(el.name, this.fieldSets(el), [], ownFields(el));
                    this.push(this.checks.equality(el));
                    this.push(this.checks.struct(el));
                    break;
                case 'fieldSet':
                    this.jsdoc([...describedLines(el), `Fields taken on with \`with ${el.name}\`.`, seeLine(el.location)]);
                    this.iface(el.name, [], [], el.fields);
                    break;
                case 'union':
                    this.union(el);
                    if (el.variants?.length) this.push(this.checks.equality(el));
                    this.push(this.checks.union(el));
                    break;
                case 'event':
                case 'error':
                    this.jsdoc([...describedLines(el), ...(el.persistent ? [PERSISTENT_LINE] : []), seeLine(el.location)]);
                    this.iface(el.name, this.fieldSets(el), [`readonly ${EVENT_TAG}: '${el.name}';`], ownFields(el));
                    break;
                case 'aggregate':
                    this.aggregate(el);
                    break;
            }
            this.out.push('');
        }
        this.persistentEvents();
        this.unions();
        const body = this.out.join('\n');
        const uses = (n: string): boolean => new RegExp(`(^|[^\\w$.])${n}\\b`, 'm').test(body);
        const runtime = ['Decimal', NO_CHANGES_TYPE, NO_EVENTS_TYPE, 'Result', 'Shape', 'Timestamp'].filter(uses);
        const values = ['distinct', 'err', 'ok', 'sameList', 'sameOptional'].filter((n) => new RegExp(`(^|[^\\w$.])${n}\\(`, 'm').test(body));
        const imports = [
            ...(runtime.length ? [`import type { ${runtime.join(', ')} } from './_runtime.js';`] : []),
            ...(values.length ? [`import { ${values.join(', ')} } from './_runtime.js';`] : []),
            ...[...this.imports].sort().map((c) => `import ${this.valueImports.has(c) ? '' : 'type '}* as ${c} from '${this.moduleOf(c)}';`),
        ];
        return [HEADER, ...imports, '', body].join('\n');
    }

    /** The events of the context that are persisted, so that code storing events can name exactly them. */
    private persistentEvents(): void {
        const events = elementsIn(this.model, this.ctx).filter((el) => el.kind === 'event' && el.persistent);
        if (!events.length) return;
        this.jsdoc([`Events of ${this.ctx} that are persisted (declared \`persistent\`).`]);
        this.line(`export type ${PERSISTENT_EVENT_TYPE} = ${events.map((e) => e.name).join(' | ')};`);
        this.out.push('');
    }

    /** Every event and every aggregate of the context, so that code handling any of them can name exactly them. */
    private unions(): void {
        const els = elementsIn(this.model, this.ctx);
        const events = els.filter((el) => el.kind === 'event');
        if (events.length) {
            this.jsdoc([`Events of ${this.ctx}.`]);
            this.line(`export type ${DOMAIN_EVENT_TYPE} = ${events.map((e) => e.name).join(' | ')};`);
            this.out.push('');
        }
        const aggregates = els.filter((el) => el.kind === 'aggregate');
        if (aggregates.length) {
            this.jsdoc([`Aggregates of ${this.ctx}.`]);
            this.line(`export type ${AGGREGATE_TYPE} = ${aggregates.map((e) => e.name).join(' | ')};`);
            this.out.push('');
        }
    }

    /** The field sets an element extends, as written from this context. */
    private fieldSets(el: ElementModel): string[] {
        return (el.fieldSets ?? []).map((f) => this.ref(f));
    }

    /**
     * Domain primitive (or ID): a branded type, the error for invalid values, and the constructor contract.
     * The constructor is implemented by hand; invariants are documented, not checked at run time.
     */
    private primitive(p: ElementModel): void {
        const base = PRIMITIVES[p.base ?? 'String'];
        const summary = p.kind === 'id' && !p.label ? [`Identifier of ${p.name}.`] : [];
        this.jsdoc([...describedLines(p), ...summary, ...invariantLines(p.invariants), seeLine(p.location)]);
        this.line(`export type ${p.name} = ${base} & { readonly __domain: '${p.id}' };`);
        this.out.push('');
        if (p.invariants.length === 0) {
            this.jsdoc([`Creates a ${p.name}. It has no invariants, so creation cannot fail.`, seeLine(p.location)]);
            this.line(`export type ${makeTypeName(p)} = (value: ${base}) => ${p.name};`);
            this.push(this.checks.primitive(p));
            return;
        }
        this.jsdoc([`A value that violates an invariant of ${p.name}.`, seeLine(p.location)]);
        this.line(`export interface ${invalidTypeName(p)} {`);
        this.line(`    readonly type: '${invalidTypeName(p)}';`);
        this.line(`    readonly value: ${base};`);
        this.line(`    /** The violated invariant. */`);
        this.line(`    readonly invariant: ${p.invariants.map((i) => `'${i.name}'`).join(' | ')};`);
        this.line('}');
        this.out.push('');
        this.jsdoc([`Creates a ${p.name}, checking its invariants: generated as \`make${p.name}${p.invariants.some((i) => !i.source) ? 'With' : ''}\`, or written by hand.`, seeLine(p.location)]);
        this.line(`export type ${makeTypeName(p)} = (value: ${base}) => Result<${p.name}, ${invalidTypeName(p)}>;`);
        this.push(this.checks.primitive(p));
    }

    /** A union: one type alias over object types tagged with the discriminator. */
    private union(u: ElementModel): void {
        const tag = u.discriminator ?? 'kind';
        this.jsdoc([...describedLines(u), seeLine(u.location)]);
        const variants = u.variants ?? [];
        if (variants.length === 0) {
            this.line(`export type ${u.name} = never;`);
            return;
        }
        this.line(`export type ${u.name} =`);
        variants.forEach((v, i) => {
            const end = i === variants.length - 1 ? ';' : '';
            const doc = [...describedLines(v), ...invariantLines(v.invariants)].flatMap((l) => comment(l).split('\n'));
            if (doc.length === 1) this.line(`    /** ${doc[0]} */`);
            else if (doc.length > 1) this.out.push('    /**', ...doc.map((l) => `     * ${l}`.trimEnd()), '     */');
            const head = `readonly ${tag}: '${v.name}';`;
            if (v.fields.length === 0) {
                this.line(`    | { ${head} }${end}`);
                return;
            }
            this.line('    | {');
            for (const l of [head, ...v.fields.flatMap((f) => this.property(f))]) this.line(`          ${l}`);
            this.line(`      }${end}`);
        });
    }

    private aggregate(agg: ElementModel): void {
        const states = agg.states ?? [];
        if (states.length === 0) {
            this.jsdoc([...describedLines(agg), ...invariantLines(agg.invariants), seeLine(agg.location)]);
            this.iface(agg.name, this.fieldSets(agg), [], ownFields(agg));
        } else {
            this.jsdoc([`Fields shared by every state of ${agg.label ? `${agg.label} (${agg.name})` : agg.name}.`, ...invariantLines(agg.invariants), seeLine(agg.location)]);
            this.iface(commonTypeName(agg), this.fieldSets(agg), [], ownFields(agg));
            for (const s of states) {
                this.out.push('');
                this.jsdoc([...describedLines(s), ...invariantLines(s.invariants), seeLine(s.location)]);
                this.iface(stateTypeName(agg, s), [commonTypeName(agg)], [`readonly ${STATE_TAG}: '${s.name}';`], s.fields);
            }
            this.out.push('');
            this.jsdoc([...describedLines(agg), seeLine(agg.location)]);
            this.line(`export type ${agg.name} = ${states.map((s) => stateTypeName(agg, s)).join(' | ')};`);
        }
        this.out.push('');
        this.shape(agg);
        this.push(this.checks.aggregate(agg));

        const commands = agg.commands ?? [];
        for (const c of commands) {
            this.out.push('');
            this.command(agg, c);
            this.push(this.requiresCheck(agg, c));
        }
        if (commands.length > 0) {
            this.out.push('');
            this.jsdoc([
                `Command contracts of ${agg.name}. Implement this interface by hand.`,
                'Commands are pure functions of the aggregate and their parameters: no I/O, no clock, no randomness. IDs and times are passed in as parameters.',
                seeLine(agg.location),
            ]);
            this.line(`export interface ${commandsInterfaceName(agg)} {`);
            for (const c of commands) {
                if (c.label) this.line(`    /** ${oneLine(c.label)} */`);
                this.line(`    readonly ${c.name}: ${commandTypeName(agg, c)};`);
            }
            this.line('}');
        }
        const events = [...new Set(commands.flatMap(emittedEvents))];
        if (events.length > 0) {
            this.out.push('');
            this.jsdoc([`Events that the commands of ${agg.name} may emit.`, seeLine(agg.location)]);
            this.line(`export type ${aggregateEventTypeName(agg)} = ${events.map((e) => this.ref(e)).join(' | ')};`);
        }
    }

    /** The fields of an aggregate as data for `decide` (`OrderShape`): the common fields, and each state's own fields. */
    private shape(agg: ElementModel): void {
        const states = agg.states ?? [];
        const list = (fields: FieldModel[]): string => `[${fields.map((f) => `'${f.name}'`).join(', ')}]`;
        this.jsdoc([`The fields of ${agg.name} as data for \`decide\`: the common fields${states.length ? ', and the fields of each state on top of them' : ''}.`, seeLine(agg.location)]);
        if (states.length === 0) {
            this.line(`export const ${shapeName(agg)}: Shape = { fields: ${list(agg.fields)} };`);
            return;
        }
        this.line(`export const ${shapeName(agg)}: Shape = {`);
        this.line(`    fields: ${list(agg.fields)},`);
        this.line(`    states: { ${states.map((s) => `${s.name}: ${list(s.fields)}`).join(', ')} },`);
        this.line('};');
    }

    private command(agg: ElementModel, c: CommandModel): void {
        const stateful = (agg.states ?? []).length > 0;
        const stateUnion = (names: string[]): string => (stateful ? unique(names).map((n) => stateTypeName(agg, n)).join(' | ') : agg.name);
        const transitions = stateful ? c.transitions : [];
        // One output for every input (as `A | B -> C`): a plain function. Outputs that depend on the input
        // (`A -> A, B -> B`, or `emits X when A ->`): a function generic over the input state, whose result is that of
        // its state, looked up in an object keyed by the source states.
        const generic = stateful && outputsVary(c.factory, transitions, c.emits);
        const input = stateUnion(transitions.flatMap((t) => t.from));
        const self = aggregateParamName(agg);
        const params = c.params.map((p) => `${p.name}: ${this.fieldType(p)}${p.cardinality === 'optional' ? ' | undefined' : ''}`);
        const errors = c.errors.length === 0 ? 'never' : c.errors.map((e) => this.ref(e)).join(' | ');
        // the outcomes of an input state (`undefined`: a factory, or no states): one per target, keyed by its name; the
        // contract holds the aggregate, the decision what to `set`
        const outcomes = (from: string | undefined, targets: string[], decision: boolean): Outcome[] =>
            (stateful ? unique(targets) : [undefined]).map((to) => ({
                key: to ?? agg.name,
                first: decision ? `set: ${this.setType(outcomeFields(agg, c, from, to).set)}` : `aggregate: ${to ? stateTypeName(agg, to) : agg.name}`,
                emits: c.emits.filter((e) => emitApplies(e, from, to)),
            }));
        const requires = requirementLines(c.requires, (e) => this.ref(e));
        const changes = c.factory ? [] : [`@changes ${c.changes.length ? c.changes.join(', ') : `none — the command changes no ${stateful ? 'common ' : ''}field`}`];
        const sources = transitions.flatMap((t) => t.from.map((from) => ({ from, to: t.to })));

        const transition = c.factory
            ? `new -> ${transitions[0]?.to.join(' | ') || agg.name}`
            : transitions.map((t) => `${t.from.join(' | ')} -> ${t.to.join(' | ')}`).join('; ');
        this.jsdoc([
            `${agg.name}.${c.name}${transition ? ` (${transition})` : ''}${c.factory ? ' — factory' : ''}`,
            ...describedLines(c),
            ...c.params.filter((p) => p.label || p.doc).map((p) => `@param ${p.name} ${[p.label, p.doc].filter(Boolean).join(' — ')}`),
            ...requires,
            ...changes,
            ...this.emitsLines(c.emits.map((e) => ({ e, when: e.when }))),
            seeLine(c.location),
        ]);
        this.line(`export type ${commandTypeName(agg, c)} = ${generic ? `<S extends ${input}>` : ''}(`);
        for (const p of [...(c.factory ? [] : [`${self}: ${generic ? 'S' : input}`]), ...params]) this.line(`    ${p},`);
        const first = transitions[0];
        if (!generic) {
            this.result(') => ', outcomes(c.factory ? undefined : first?.from[0], first?.to ?? [], false), errors, '', ';');
        } else {
            this.line(') => {');
            for (const { from, to } of sources) {
                this.memberDoc(this.emitsLines(this.emitsFrom(c, from, to)));
                this.result(`    readonly ${from}: `, outcomes(from, to, false), errors, '    ', ';');
            }
            this.line(`}[S['${STATE_TAG}']];`);
        }

        // The decision: one handler per source state, or one function for a factory and without states.
        const keyed = stateful && !c.factory;
        const outcomeLines = keyed
            ? sources.flatMap(({ from, to }) => unique(to).map((t) => this.outcomeLine(agg, c, from, t)))
            : (stateful ? unique(first?.to ?? []) : [undefined]).map((t) => this.outcomeLine(agg, c, undefined, t));
        this.out.push('');
        this.jsdoc([
            `${agg.name}.${c.name}, decided ${keyed ? 'per source state' : 'by one function'}; implement it with \`decide(${shapeName(agg)}, …)\` from the runtime.`,
            `Each outcome gives the fields of \`set\`, and \`decide\` makes the aggregate${c.factory ? ' from them' : ', taking the other fields from the input'}.`,
            ...requires,
            ...changes,
            ...outcomeLines,
            ...(keyed ? [] : this.emitsLines(c.emits.map((e) => ({ e, when: e.when })))),
            seeLine(c.location),
        ]);
        if (!keyed) {
            this.line(`export type ${decisionTypeName(agg, c)} = (`);
            for (const p of [...(c.factory ? [] : [`${self}: ${input}`]), ...params]) this.line(`    ${p},`);
            this.result(') => ', outcomes(undefined, first?.to ?? [], true), errors, '', ';');
            return;
        }
        this.line(`export type ${decisionTypeName(agg, c)} = {`);
        for (const { from, to } of sources) {
            this.memberDoc(this.emitsLines(this.emitsFrom(c, from, to)));
            this.result(`    readonly ${from}: (${[`${self}: ${stateTypeName(agg, from)}`, ...params].join(', ')}) => `, outcomes(from, to, true), errors, '    ', ';');
        }
        this.line('};');
    }

    /** The generated check of a command's requirements, with the parameters of its contract. */
    private requiresCheck(agg: ElementModel, c: CommandModel): string[] {
        const states = agg.states ?? [];
        const sources = unique(c.transitions.flatMap((t) => t.from));
        const input = states.length ? sources.map((n) => stateTypeName(agg, n)).join(' | ') : agg.name;
        const subject = c.factory ? undefined : { name: aggregateParamName(agg), type: input };
        const ps = c.params.map((p) => ({ name: p.name, type: `${this.fieldType(p)}${p.cardinality === 'optional' ? ' | undefined' : ''}` }));
        return this.checks.requires(agg, c, commandTypeName(agg, c), subject, ps);
    }

    /** The entries of `emits` for a source state, with `when` reduced to what still selects among its targets. */
    private emitsFrom(c: CommandModel, from: string, targets: string[]): { e: EmitModel; when?: OutcomePatternModel }[] {
        return c.emits
            .filter((e) => targets.some((to) => emitApplies(e, from, to)))
            .map((e) => ({ e, when: e.when?.to.length && !targets.every((to) => e.when!.to.includes(to)) ? { from: [], to: e.when.to } : undefined }));
    }

    /** What the decision gives for an outcome, and what `decide` carries over and drops, in words. */
    private outcomeLine(agg: ElementModel, c: CommandModel, from: string | undefined, to: string | undefined): string {
        const head = c.factory ? `new -> ${to ?? agg.name}` : to ? `${from} -> ${to}` : agg.name;
        if (c.factory) return `${head} — set: every field`;
        const { set, carried, dropped } = outcomeFields(agg, c, from, to);
        const names = (fields: FieldModel[]): string => fields.map((f) => f.name).join(', ');
        const fresh = (f: FieldModel): boolean => !agg.fields.includes(f) && !carried.includes(f) && !c.changes.includes(f.name);
        return [
            `${head} — set: ${set.length ? set.map((f) => `${f.name}${fresh(f) ? ` (new in ${to})` : ''}`).join(', ') : 'nothing'}`,
            ...(carried.length ? [`carried over: ${names(carried)}`] : []),
            ...(dropped.length ? [`dropped: ${names(dropped)}`] : []),
        ].join('; ');
    }

    /** The type of the `set` of an outcome: every field required, an optional one cleared with `undefined`. */
    private setType(fields: FieldModel[]): string {
        if (fields.length === 0) return NO_CHANGES_TYPE;
        return `{ ${fields.map((f) => `readonly ${f.name}: ${this.fieldType(f)}${f.cardinality === 'optional' ? ' | undefined' : ''}`).join('; ')} }`;
    }

    /** A JSDoc block for a member of a type (single line when short). */
    private memberDoc(lines: string[]): void {
        const doc = lines.flatMap((l) => comment(l).split('\n'));
        if (doc.length === 1) this.line(`    /** ${doc[0]} */`);
        else if (doc.length > 1) this.out.push('    /**', ...doc.map((l) => `     * ${l}`), '     */');
    }

    /**
     * `Result<…>` of a command or a decision, starting with `head` on the current line: the success value is keyed by
     * the outcome's state (`{ readonly Confirmed: { aggregate, events } }`, or `{ set, events }` in a decision); with
     * several outcomes, a union whose branches mark the other keys `?: never`, so that a value holds exactly one outcome.
     */
    private result(head: string, outcomes: Outcome[], errors: string, indent: string, end: string): void {
        const body = (o: Outcome, pad: string): string[] => [
            `${pad}readonly ${o.key}: {`,
            `${pad}    readonly ${o.first};`,
            `${pad}    readonly events: ${this.events(o.emits)};`,
            `${pad}};`,
        ];
        if (outcomes.length === 1) {
            this.line(`${head}Result<{`);
            for (const l of body(outcomes[0], `${indent}    `)) this.line(l);
            this.line(`${indent}}, ${errors}>${end}`);
            return;
        }
        this.line(`${head}Result<`);
        outcomes.forEach((o, i) => {
            this.line(`${indent}    | {`);
            for (const l of body(o, `${indent}          `)) this.line(l);
            for (const other of outcomes) if (other !== o) this.line(`${indent}          readonly ${other.key}?: never;`);
            this.line(`${indent}      }${i === outcomes.length - 1 ? ',' : ''}`);
        });
        this.line(`${indent}    ${errors}`);
        this.line(`${indent}>${end}`);
    }

    /** The `events` of an outcome: one property per event, keyed by its name, typed by its multiplicity. */
    private events(emits: EmitModel[]): string {
        if (emits.length === 0) return NO_EVENTS_TYPE;
        const props = emits.map((e) => {
            const t = this.ref(e.event);
            const key = e.event.slice(e.event.indexOf('.') + 1);
            if (e.lower === 1 && e.upper === 1) return `readonly ${key}: ${t}`;
            if (e.lower === 0 && e.upper === 1) return `readonly ${key}?: ${t}`;
            if (e.lower === 1 && e.upper === undefined) return `readonly ${key}: readonly [${t}, ...${t}[]]`;
            if (e.lower === 0 && e.upper === undefined) return `readonly ${key}: readonly ${t}[]`;
            return `/** ${times(e).words} */ readonly ${key}: readonly ${t}[]`;
        });
        return `{ ${props.join('; ')} }`;
    }

    /** `@emits` lines: what each entry means, in words. `when` is the condition to state (absent: on every success). */
    private emitsLines(entries: { e: EmitModel; when?: OutcomePatternModel }[]): string[] {
        if (entries.length === 0) return ['@emits nothing'];
        return entries.map(({ e, when }) => {
            const { words, unchecked } = times(e);
            return `@emits ${this.ref(e.event)}${e.multiplicity} — ${words} ${condition(when)}${unchecked ? ' (not checked by the types)' : ''}`;
        });
    }

    private iface(name: string, bases: string[], extra: string[], fields: FieldModel[]): void {
        const lines = [...extra, ...fields.flatMap((f) => this.property(f))];
        const ext = bases.length ? ` extends ${bases.join(', ')}` : '';
        if (lines.length === 0) {
            this.line(`export interface ${name}${ext} {}`);
            return;
        }
        this.line(`export interface ${name}${ext} {`);
        for (const l of lines) this.line(`    ${l}`);
        this.line('}');
    }

    private property(f: FieldModel): string[] {
        const doc = [f.label, f.doc].filter(Boolean).join(' — ');
        const prefix = doc ? [`/** ${oneLine(doc)} */`] : [];
        const ref = f.kind === 'references' && f.target ? ` // -> ${f.target}` : '';
        if (f.cardinality === 'optional') return [...prefix, `readonly ${f.name}?: ${this.fieldType(f)};${ref}`];
        return [...prefix, `readonly ${f.name}: ${this.fieldType(f)};${ref}`];
    }

    private fieldType(f: FieldModel): string {
        const t = this.typeExpr(f.type);
        switch (f.cardinality) {
            case 'many':
                return `readonly ${t}[]`;
            case 'nonEmpty':
                return `readonly [${t}, ...${t}[]]`;
            default:
                return t;
        }
    }

    private typeExpr(t: TypeExpr): string {
        return t.kind === 'primitive' ? PRIMITIVES[t.name] : this.ref(t.ref);
    }

    /** TypeScript reference to a qualified element name, importing other contexts as namespaces. */
    private ref(qname: string): string {
        const dot = qname.indexOf('.');
        const ctx = qname.slice(0, dot);
        const name = qname.slice(dot + 1);
        if (ctx === this.ctx) return name;
        this.imports.add(ctx);
        return `${ctx}.${name}`;
    }

    /** Emits a JSDoc block (single line when short); nothing for an empty list. */
    private jsdoc(lines: string[]): void {
        const all = lines.flatMap((l) => comment(l).split('\n'));
        if (all.length === 0) return;
        if (all.length === 1) this.out.push(`/** ${all[0]} */`);
        else this.out.push('/**', ...all.map((l) => ` * ${l}`.trimEnd()), ' */');
    }

    private line(text: string): void {
        this.out.push(text);
    }
}
