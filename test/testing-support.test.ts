// `domaintrail/testing`, the support of the generated contract tests shipped as a subpath of the package (ADR 0028,
// decision 5): its version and the check the generated test modules run when they are loaded. In the repository the
// root tsconfig.json maps it to its source, testing/index.ts; scripts/build.ts builds it into dist/ for the package.
import { describe, expect, test } from 'bun:test';
import { checkVersion, VERSION } from 'domaintrail/testing';
import pkg from '../package.json' with { type: 'json' };

describe('domaintrail/testing', () => {
    test("exports the package's version", () => {
        expect(VERSION).toBe(pkg.version);
    });

    test('is exported by the package from dist/, with its declarations', () => {
        expect(pkg.exports['./testing']).toEqual({ types: './dist/testing.d.ts', default: './dist/testing.js' });
        expect(pkg.files).toContain('dist');
        expect(pkg.peerDependenciesMeta['fast-check']).toEqual({ optional: true });
    });

    test('accepts tests generated by the same release line, as with ^version', () => {
        const [major, minor, patch] = VERSION.split(/[.-]/).map(Number);
        expect(() => checkVersion(VERSION)).not.toThrow();
        if (patch > 0) expect(() => checkVersion(`${major}.${minor}.${patch - 1}`)).not.toThrow();
        if (major > 0 && minor > 0) expect(() => checkVersion(`${major}.${minor - 1}.0`)).not.toThrow();
    });

    test('rejects tests generated by a newer version or another release line, saying what to do', () => {
        const [major, minor, patch] = VERSION.split(/[.-]/).map(Number);
        const rejected = [
            `${major}.${minor}.${patch + 1}`,
            `${major + 1}.0.0`,
            ...(major === 0 ? [`0.${minor + 1}.0`, ...(minor > 0 ? [`0.${minor - 1}.0`] : [])] : []),
            'next',
        ];
        for (const v of rejected) {
            expect(() => checkVersion(v)).toThrow(
                `These contract tests were generated by domaintrail ${v}, but domaintrail/testing is ${VERSION}. Run \`dt generate ts\` again with this domaintrail, or install the domaintrail they were generated with (^${v}).`,
            );
        }
    });
});
