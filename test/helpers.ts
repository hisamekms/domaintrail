import { cp, mkdir, mkdtemp, readdir, symlink, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import * as path from 'node:path';
import { type Analysis, analyze } from '@domaintrail/analysis';
import { type Diagnostic, type SourceFile } from '@domaintrail/kernel';
import { createViewService, ElkLayoutEngine } from '@domaintrail/visualization';
import type { ViewPayload } from '@domaintrail/visualization/protocol';

const ROOT = path.join(import.meta.dir, '..');
export const EXAMPLES = path.join(ROOT, 'examples', 'shop');

/**
 * Gives a temporary project `dir` a node_modules as if it had domaintrail as a dev dependency: the entries of this
 * repository's node_modules (fast-check, the types of Bun), and a `domaintrail` whose `domaintrail/testing` (the
 * support of the generated contract tests) is its source, testing/index.ts, so that no build is needed.
 */
export async function linkNodeModules(dir: string): Promise<void> {
    const modules = path.join(dir, 'node_modules');
    await mkdir(modules);
    for (const entry of await readdir(path.join(ROOT, 'node_modules'))) await symlink(path.join(ROOT, 'node_modules', entry), path.join(modules, entry));
    const pkg = path.join(modules, 'domaintrail');
    await mkdir(pkg);
    await writeFile(path.join(pkg, 'package.json'), JSON.stringify({ name: 'domaintrail', type: 'module', exports: { './testing': './testing/index.ts' } }));
    await symlink(path.join(ROOT, 'testing'), path.join(pkg, 'testing'));
}

/**
 * Generated code with the version of domaintrail that the contract tests state (`testing.checkVersion('0.6.0')`)
 * replaced by `<version>`, so that the tests comparing generated code with a baseline do not change with each release.
 */
export const withoutVersion = (text: string): string => text.replace(/(generated by domaintrail |checkVersion\(')\d+\.\d+\.\d+[^\s':]*/g, '$1<version>');

/** Analyzes inline sources; keys are file names. */
export function check(files: Record<string, string>): Promise<Analysis> {
    return analyze(Object.entries(files).map(([p, text]) => ({ path: p, text })));
}

/** Analyzes a single context body wrapped in `context Sales { ... }`. */
export function checkSales(body: string): Promise<Analysis> {
    return check({ 'sales.dt': `context Sales {\n${body}\n}\n` });
}

export const codes = (a: Analysis): string[] => a.diagnostics.filter((d) => d.severity === 'error').map((d) => d.code);

export function only(a: Analysis, code: string): Diagnostic[] {
    return a.diagnostics.filter((d) => d.code === code);
}

export async function tempCopyOfExamples(): Promise<string> {
    const dir = await mkdtemp(path.join(tmpdir(), 'domaintrail-'));
    await cp(EXAMPLES, dir, {
        recursive: true,
        filter: (src) =>
            !path
                .relative(EXAMPLES, src)
                .split(path.sep)
                .some((part) => part === 'generated' || part === '.dt'),
    });
    return dir;
}

/**
 * The Live View's payloads for `steps` of sources, one refresh each, from the view service over in-memory ports (no
 * git, no saved layouts): what the page is sent, with the diff of each step against the one before.
 */
export async function viewPayloads(...steps: (readonly SourceFile[])[]): Promise<ViewPayload[]> {
    let sources: readonly SourceFile[] = [];
    const engine = new ElkLayoutEngine();
    const service = createViewService({
        root: '/workspace',
        engine,
        workspace: { readSources: async () => sources },
        layoutStore: { load: async () => new Map(), save: async () => {} },
        git: {
            resolveCommit: (ref) => Promise.reject(new Error(`no git: ${ref}`)),
            sourcesAt: async () => [],
            listRefs: async () => ({ branches: [], tags: [], commits: [] }),
            gitDirs: async () => undefined,
        },
    });
    const payloads: ViewPayload[] = [];
    try {
        for (const step of steps) {
            sources = step;
            payloads.push(await service.refresh());
        }
    } finally {
        engine.dispose();
    }
    return payloads;
}
