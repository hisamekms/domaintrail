/**
 * Generates one module per bounded context, plus a runtime and an index in every directory written to.
 * `dirs` places contexts in directories (`/`-separated, relative to the output directory; default: the output
 * directory itself); each index re-exports only the contexts in its directory. With `tests`, also the contract tests
 * (ADR 0020) into `tests.dir`. `policies` gives the mode of each context's policies (absent: `optional`). `modules`
 * gives the module of each context written into another package (ADR 0028): code in another directory imports the
 * context from it, and the context's tests are written into `<its directory>/tests`. Requires a model without errors.
 */
export function generateTypeScript(
    model: DomainModel,
    dirs: Readonly<Record<string, string>> = {},
    tests?: TestsOptions,
    policies: Readonly<Record<string, PolicyMode>> = {},
    modules: Readonly<Record<string, string>> = {},
): GeneratedFile[] {
    const dirOf = (ctx: string): string => posix.normalize(dirs[ctx] || '.');
    // a context of another package by its module, one of the same directory by relative path
    const moduleOf = (from: string, ctx: string): string => (modules[ctx] && dirOf(ctx) !== from ? modules[ctx] : moduleSpecifier(from, dirOf(ctx), ctx));
    const testsDirs = Object.fromEntries(Object.keys(modules).map((c) => [c, posix.join(dirOf(c), 'tests')]));
    const files: GeneratedFile[] = [];
    for (const dir of new Set(contextNames(model).map(dirOf))) {
        const contexts = contextNames(model).filter((c) => dirOf(c) === dir);
        files.push({ path: posix.join(dir, '_runtime.ts'), content: RUNTIME });
        for (const ctx of contexts) {
            files.push({
                path: posix.join(dir, `${ctx}.ts`),
                content: new ContextEmitter(model, ctx, (other) => moduleOf(dir, other), policies[ctx] ?? 'optional').emit(),
            });
        }
        const index = [HEADER, `export * from './_runtime.js';`, ...contexts.map((c) => `export * as ${c} from './${c}.js';`), ''].join('\n');
        files.push({ path: posix.join(dir, 'index.ts'), content: index });
    }
    if (tests)
        files.push(
            ...generateTests(model, HEADER, { ...tests, dir: posix.normalize(tests.dir), policies, dirs: testsDirs, modules }, (from, ctx) =>
                // the tests in a context's own package import it by relative path
                modules[ctx] && testsDirs[ctx] !== from ? modules[ctx] : moduleSpecifier(from, dirOf(ctx), ctx),
            ),
        );
    return files;
}

/** Import specifier of the module of `ctx` in directory `to`, from a module in directory `from`. */
function moduleSpecifier(from: string, to: string, ctx: string): string {
    const rel = posix.relative(from, to);
    if (rel === '') return `./${ctx}.js`;
    return `${rel === '..' || rel.startsWith('../') ? '' : './'}${rel}/${ctx}.js`;
}

/** Text that is safe inside a block comment. */
/** JavaScript line terminators: any of them ends a `//` comment. */
const LINE_TERMINATORS = /\r\n|[\n\r\u2028\u2029]/g;

/** Text that is safe inside a block comment (line breaks normalized to `\n`, `*\/` defused). */
const comment = (s: string): string => s.replace(LINE_TERMINATORS, '\n').replace(/\*\//g, '* /');

/** Text that is safe inside a `//` line comment or on one line of a block comment. */
const oneLine = (s: string): string => comment(s).replace(/\n+/g, ' ');

/** Japanese name and description lines of a declaration. */
const describedLines = (d: Described): string[] => [d.label, d.doc].filter((x): x is string => !!x);

/** JSDoc line of an event declared `persistent`. */
const PERSISTENT_LINE = '@persistent Persisted: storing this event is part of its contract.';

/** JSDoc lines of invariants; one declared without an expression says so. */
const invariantLines = (invs: readonly InvariantModel[]): string[] =>
    invs.map((i) => `@invariant ${i.name}${i.label ? ` (${i.label})` : ''}: ${i.source ?? 'not expressed in the DSL'}`);

/**
 * JSDoc line pointing to the DSL declaration a generated declaration comes from, as `dt check` prints it (relative to
 * the config root, `/`-separated), e.g. `@see sales/order.dt:41`.
 */
const seeLine = (loc: Location): string => `@see ${loc.file.replace(/\\/g, '/')}:${loc.line}`;

/** JSDoc lines of a command's requirements; one declared without an expression says so. */
const requirementLines = (reqs: readonly RequirementModel[], error: (qname: string) => string): string[] =>
    reqs.map((r) => `@requires ${r.name}${r.label ? ` (${r.label})` : ''} else ${error(r.error)}: ${r.source ?? 'not expressed in the DSL'}`);

const unique = (names: readonly string[]): string[] => [...new Set(names)];

/** An outcome of a command: the key of its success value (the target state), its first property and the events. */
interface Outcome {
    key: string;
    /** `aggregate: …` in the contract, `set: …` in the decision. */
    first: string;
    emits: EmitModel[];
}

/** How often an `emits` entry emits its event, in words; `unchecked` when the types do not enforce the bounds. */
function times(e: EmitModel): { words: string; unchecked: boolean } {
    const { lower, upper } = e;
    if (lower === 1 && upper === 1) return { words: 'exactly once', unchecked: false };
    if (lower === 0 && upper === 1) return { words: 'at most once', unchecked: false };
    if (lower === 0 && upper === undefined) return { words: 'zero or more', unchecked: false };
    if (lower === 1 && upper === undefined) return { words: 'one or more', unchecked: false };
    if (upper === undefined) return { words: `${lower} or more`, unchecked: true };
    return { words: lower === upper ? `exactly ${lower} times` : `between ${lower} and ${upper}`, unchecked: true };
}

/** `A`, `A or B`, `A, B or C`. */
const or = (names: readonly string[]): string => (names.length < 2 ? names.join('') : `${names.slice(0, -1).join(', ')} or ${names[names.length - 1]}`);

/** When an `emits` entry applies, in words. */
function condition(w: OutcomePatternModel | undefined): string {
    if (!w || (w.from.length === 0 && w.to.length === 0)) return 'when the command succeeds';
    if (w.to.length === 0) return `when it comes from ${or(w.from)}`;
    if (w.from.length === 0) return `when it ends in ${or(w.to)}`;
    return `when it comes from ${or(w.from)} and ends in ${or(w.to)}`;
}

class ContextEmitter {
    private readonly imports = new Set<string>();
    /** Contexts whose module is imported as a value (its generated checks are called), not only for types. */
    private readonly valueImports = new Set<string>();
    /** Contexts named by a `{@link}` in a doc comment; imported for types only, so that the link resolves in editors. */
    private readonly linked = new Set<string>();
    private readonly out: string[] = [];
    private readonly checks: CheckWriter;
    /** The `…Input` types written, once each. */
    private readonly inputs = new Set<string>();

    constructor(
        private readonly model: DomainModel,
        private readonly ctx: string,
        /** Import specifier of another context's module. */
        private readonly moduleOf: (ctx: string) => string,
        private readonly policies: PolicyMode,
    ) {
        this.checks = new CheckWriter({
            model,
            ctx,
            typeRef: (qname) => this.ref(qname),
            valueRef: (qname, name) => {
                const ctx = qname.slice(0, qname.indexOf('.'));
                if (ctx === this.ctx) return name;
                this.imports.add(ctx);
                this.valueImports.add(ctx);
                return `${ctx}.${name}`;
            },
            fieldType: (f) => this.fieldType(f),
            jsdoc: (lines, loc) => {
                const start = this.out.length;
                this.jsdoc([...lines, seeLine(loc)]);
                return this.out.splice(start);
            },
        });
    }

    /** Lines of generated checks, after a blank line (nothing when there are none). */
    private push(lines: string[]): void {
        if (lines.length) this.out.push('', ...lines);
    }

    emit(): string {
        for (const el of elementsIn(this.model, this.ctx)) {
            switch (el.kind) {
                case 'id':
                case 'primitive':
                    this.primitive(el);
                    break;
                case 'verified':
                    this.verified(el);
                    break;
                case 'enum':
                    this.jsdoc([...describedLines(el), seeLine(el.location)]);
                    if (!el.values.length) {
                        this.line(`export type ${el.name} = never;`);
                    } else if (el.values.some((v) => v.label)) {
                        this.line(`export type ${el.name} =`);
                        el.values.forEach((v, i) => {
                            this.line(`    | '${v.name}'${i === el.values.length - 1 ? ';' : ''}${v.label ? ` // ${oneLine(v.label)}` : ''}`);
                        });
                    } else {
                        this.line(`export type ${el.name} = ${el.values.map((v) => `'${v.name}'`).join(' | ')};`);
                    }
                    break;
                case 'valueObject':
                case 'entity':
                    this.jsdoc([...describedLines(el), ...invariantLines(el.invariants), seeLine(el.location)]);
                    this.iface(el.name, this.fieldSets(el), [], ownFields(el));
                    this.push(this.checks.equality(el));
                    this.push(this.checks.struct(el));
                    break;
                case 'fieldSet':
                    this.jsdoc([...describedLines(el), `Fields taken on with \`with ${el.name}\`.`, seeLine(el.location)]);
                    this.iface(el.name, [], [], el.fields);
                    break;
                case 'union':
                    this.union(el);
                    if (el.variants.length) this.push(this.checks.equality(el));
                    this.push(this.checks.union(el));
                    break;
                case 'event':
                case 'error':
                    this.jsdoc([...describedLines(el), ...(el.kind === 'event' && el.persistent ? [PERSISTENT_LINE] : []), seeLine(el.location)]);
                    this.iface(el.name, this.fieldSets(el), [`readonly ${EVENT_TAG}: '${el.id}';`], ownFields(el));
                    break;
                case 'aggregate':
                    this.aggregate(el);
                    break;
                case 'policy':
                    this.policy(el);
                    break;
            }
            this.out.push('');
        }
        this.persistentEvents();
        this.unions();
        this.policyHandlers();
        this.commandErrors();
        const body = this.out.join('\n');
        // names in doc comments (labels, descriptions) are not uses
        const code = this.out
            .flatMap((chunk) => chunk.split('\n'))
            .filter((line) => !/^\s*(\/\*\*|\*|\/\/)/.test(line))
            .join('\n');
        const uses = (n: string): boolean => new RegExp(`(^|[^\\w$.])${n}\\b`, 'm').test(code);
        const runtime = [
            'Availability',
            'CommandNotForKind',
            'CommandUnavailable',
            'Decimal',
            'Err',
            NO_CHANGES_TYPE,
            NO_EVENTS_TYPE,
            'PlainDate',
            'PlainTime',
            'PlainYearMonth',
            'PlainDateTime',
            'ZonedDateTime',
            'TimeZone',
            'Result',
            'Shape',
            'Timestamp',
        ].filter(uses);
        const values = [
            'availableCommands',
            'decimalCompare',
            'distinct',
            'err',
            'fromAnyState',
            'isAvailable',
            'ok',
            'sameList',
            'sameOptional',
            'zonedCompare',
        ].filter((n) => new RegExp(`(^|[^\\w$.])${n}\\(`, 'm').test(code));
        const imports = [
            ...(runtime.length ? [`import type { ${runtime.join(', ')} } from './_runtime.js';`] : []),
            ...(values.length ? [`import { ${values.join(', ')} } from './_runtime.js';`] : []),
            ...[...new Set([...this.imports, ...this.linked])].sort().flatMap((c) => [
                // a context only linked is otherwise unused: TypeScript counts the link, linters do not
                ...(this.imports.has(c) ? [] : ['// oxlint-disable-next-line no-unused-vars -- only named by {@link} in doc comments']),
                `import ${this.valueImports.has(c) ? '' : 'type '}* as ${c} from '${this.moduleOf(c)}';`,
            ]),
        ];
        return [HEADER, ...imports, '', body].join('\n');
    }

    /** Declared decision errors, keyed by aggregate and command, including commands that cannot return an error. */
    private commandErrors(): void {
        const commands = elementsIn(this.model, this.ctx)
            .filter((el): el is AggregateModel => el.kind === 'aggregate')
            .flatMap((agg) => agg.commands.map((command) => ({ agg, command })));
        if (!commands.length) return;
        this.line('/** Error `type` values each command decision can return, as declared by the model. */');
        this.line(`export const ${COMMAND_ERRORS_NAME} = {`);
        for (const { agg, command } of commands) {
            const errors = command.errors.map(quote).join(', ');
            this.line(`    ${quote(`${agg.name}.${command.name}`)}: [${errors}],`);
        }
        this.line('} as const;');
        this.out.push('');
    }

    /** The events of the context that are persisted, so that code storing events can name exactly them. */
    private persistentEvents(): void {
        const events = elementsIn(this.model, this.ctx).filter((el) => el.kind === 'event' && el.persistent);
        if (!events.length) return;
        this.jsdoc([`Events of ${this.ctx} that are persisted (declared \`persistent\`).`]);
        this.line(`export type ${PERSISTENT_EVENT_TYPE} = ${events.map((e) => e.name).join(' | ')};`);
        this.out.push('');
    }

    /** Every event and every aggregate of the context, so that code handling any of them can name exactly them. */
    private unions(): void {
        const els = elementsIn(this.model, this.ctx);
        const events = els.filter((el) => el.kind === 'event');
        if (events.length) {
            this.jsdoc([`Events of ${this.ctx}.`]);
            this.line(`export type ${DOMAIN_EVENT_TYPE} = ${events.map((e) => e.name).join(' | ')};`);
            this.out.push('');
        }
        const aggregates = els.filter((el) => el.kind === 'aggregate');
        if (aggregates.length) {
            this.jsdoc([`Aggregates of ${this.ctx}.`]);
            this.line(`export type ${AGGREGATE_TYPE} = ${aggregates.map((e) => e.name).join(' | ')};`);
            this.out.push('');
        }
    }

    /**
     * A policy: the type of its handler, from the event to what the application needs to run the command (`…Input`,
     * written before the first policy that runs the command). The rule is "eventually": nothing here says how.
     */
    private policy(p: PolicyElement): void {
        const { event, aggregate, command } = p.policy;
        const agg = elementOf(this.model, aggregate);
        const c = agg?.kind === 'aggregate' ? agg.commands.find((x) => x.name === command) : undefined;
        if (agg?.kind !== 'aggregate' || !c) return; // the model has no errors when generated
        const input = inputTypeName(agg, c);
        if (!this.inputs.has(input)) {
            this.inputs.add(input);
            this.input(agg, c);
            this.out.push('');
        }
        const target = `${agg.name}.${c.name}`;
        this.jsdoc([
            `Policy ${p.name}: when ${this.ref(event)} happens, ${target} is run — eventually.`,
            ...describedLines(p),
            'The handler computes what the command needs from the event; your application runs the command. Any mechanism satisfies the rule: the same use case, an event bus, a batch. Data from elsewhere comes in through the closures your code builds; a rejected promise means the input cannot be computed now.',
            this.policies === 'required'
                ? `Required (\`generate.ts.policies\`): implement it in \`${policyHandlersName(this.ctx)}\`, which the contract tests take.`
                : `Optional (\`generate.ts.policies\`): nothing requires an implementation.`,
            seeLine(p.location),
        ]);
        this.line(`export type ${policyTypeName(p)} = (event: ${this.ref(event)}) => Promise<${input}>;`);
    }

    /** What the application needs to run a command: its arguments by name, after the aggregate's ID unless a factory. */
    private input(agg: AggregateModel, c: CommandModel): void {
        const id = agg.fields.find((f) => f.name === 'id');
        const self = !c.factory && id ? [`/** The ${agg.name} to run the command on. */`, `readonly ${aggregateParamName(agg)}: ${this.fieldType(id)};`] : [];
        this.jsdoc([
            `What the application needs to run ${agg.name}.${c.name}${c.factory ? ' (a factory)' : ''}: ${c.factory ? 'its parameters' : `the ID of the ${agg.name}, then its parameters`}, by name.`,
            'Given by the handlers of the policies that run it.',
            seeLine(c.location),
        ]);
        const lines = [...self, ...c.params.flatMap((f) => this.property(f))];
        if (!lines.length) {
            this.line(`export interface ${inputTypeName(agg, c)} {}`);
            return;
        }
        this.line(`export interface ${inputTypeName(agg, c)} {`);
        for (const l of lines) this.line(`    ${l}`);
        this.line('}');
    }

    /** With `required` policies: every policy of the context with its handler, implemented by your code. */
    private policyHandlers(): void {
        const policies = elementsIn(this.model, this.ctx).filter((el) => el.kind === 'policy');
        if (this.policies !== 'required' || !policies.length) return;
        this.jsdoc([`The handlers of the policies of ${this.ctx}, one per policy: required (\`generate.ts.policies\`), and taken by the contract tests.`]);
        this.line(`export interface ${policyHandlersName(this.ctx)} {`);
        for (const p of policies) {
            if (p.label) this.line(`    /** ${oneLine(p.label)} */`);
            this.line(`    readonly ${p.name}: ${policyTypeName(p)};`);
        }
        this.line('}');
        this.out.push('');
    }

    /** The field sets an element extends, as written from this context. */
    private fieldSets(el: Extract<ElementModel, { readonly fieldSets: unknown }>): string[] {
        return el.fieldSets.map((f) => this.ref(f));
    }

    /**
     * Domain primitive (or ID): a branded type, the error for invalid values, and the constructor contract.
     * The constructor is implemented by hand; invariants are documented, not checked at run time.
     */
    private primitive(p: DomainPrimitive): void {
        const base = PRIMITIVES[p.base];
        const invariants = primitiveInvariants(p);
        const summary = p.kind === 'id' && !p.label ? [`Identifier of ${p.name}.`] : [];
        const make = `make${p.name}${invariants.some((i) => !i.source) ? 'With' : ''}`;
        const noCast = `Make it with \`${make}\`; never \`as ${p.name}\` (see dt guide lint).`;
        this.jsdoc([...describedLines(p), ...summary, ...invariantLines(invariants), noCast, seeLine(p.location)]);
        this.line(`export type ${p.name} = ${base} & { readonly __domain: '${p.id}' };`);
        this.out.push('');
        if (invariants.length === 0) {
            this.jsdoc([`Creates a ${p.name}. It has no invariants, so creation cannot fail.`, seeLine(p.location)]);
            this.line(`export type ${makeTypeName(p)} = (value: ${base}) => ${p.name};`);
            this.push(this.checks.primitive(p));
            return;
        }
        this.jsdoc([`A value that violates an invariant of ${p.name}.`, seeLine(p.location)]);
        this.line(`export interface ${invalidTypeName(p)} {`);
        this.line(`    readonly type: '${this.ctx}.${invalidTypeName(p)}';`);
        this.line(`    readonly value: ${base};`);
        this.line(`    /** The violated invariant. */`);
        this.line(`    readonly invariant: ${invariants.map((i) => `'${i.name}'`).join(' | ')};`);
        this.line('}');
        this.out.push('');
        this.jsdoc([
            `Creates a ${p.name}, checking its invariants: generated as \`make${p.name}${invariants.some((i) => !i.source) ? 'With' : ''}\`, or written by hand.`,
            seeLine(p.location),
        ]);
        this.line(`export type ${makeTypeName(p)} = (value: ${base}) => Result<${p.name}, ${invalidTypeName(p)}>;`);
        this.push(this.checks.primitive(p));
    }

    /**
     * A verified type (ADR 0023): the base type with a property of its own, so that only a value the factory made (and
     * asserted) is one, a value of the base is not, and the verifications of a chain combine; and the factory contract,
     * async since the check reads the world outside the aggregate.
     */
    private verified(v: ElementOf<'verified'>): void {
        const { of, for: context, errors } = v.verified;
        const base = this.typeExpr(of);
        const contextType = context && this.typeExpr(context.type);
        this.jsdoc([
            ...describedLines(v),
            `A value of ${base} for which ${makeTypeName(v)} made a check outside the aggregate. Evidence of a check made at that moment, not a guarantee when the aggregate is saved — keep enforcing it where it is stored (e.g. a unique index).`,
            `Make it with your \`${makeTypeName(v)}\` factory; never \`as ${v.name}\` outside it (see dt guide lint).`,
            seeLine(v.location),
        ]);
        this.line(`export type ${v.name} = ${base} & { readonly '${VERIFIED_PREFIX}${v.id}': true };`);
        this.out.push('');
        const given = context ? `, given the ${contextType}${context.optional ? ' (or `undefined`)' : ''} the check needs` : '';
        this.jsdoc([
            `Checks a value of ${base}${given}, and returns it as ${v.name} when the check passes. Written by hand (with repositories and services): the only code that may assert the type.`,
            ...(context?.optional
                ? [
                      `The context is required even when there is none: pass \`undefined\` explicitly. Were it optional, a call that forgot it would compile, and the check would then not leave out the one it should (e.g. report an aggregate's own value as taken).`,
                  ]
                : []),
            `The errors of the \`Result\` are the domain's answers${errors.length ? `: ${or(errors.map((e) => this.ref(e)))}` : ', none here'}. A rejected promise means the check could not be made (the repository or a service failed): not a domain error, it is left to the application's edge (an error response, a retry).`,
            seeLine(v.location),
        ]);
        const params = [`value: ${base}`, ...(context ? [`context: ${contextType}${context.optional ? ' | undefined' : ''}`] : [])];
        const error = errors.length ? errors.map((e) => this.ref(e)).join(' | ') : 'never';
        this.line(`export type ${makeTypeName(v)} = (${params.join(', ')}) => Promise<Result<${v.name}, ${error}>>;`);
    }

    /** A union: one type alias over object types tagged with the discriminator. */
    private union(u: UnionModel): void {
        const tag = u.discriminator;
        this.jsdoc([...describedLines(u), seeLine(u.location)]);
        const variants = u.variants;
        if (variants.length === 0) {
            this.line(`export type ${u.name} = never;`);
            return;
        }
        this.line(`export type ${u.name} =`);
        variants.forEach((v, i) => {
            const end = i === variants.length - 1 ? ';' : '';
            const doc = [...describedLines(v), ...invariantLines(v.invariants)].flatMap((l) => comment(l).split('\n'));
            if (doc.length === 1) this.line(`    /** ${doc[0]} */`);
            else if (doc.length > 1) this.out.push('    /**', ...doc.map((l) => `     * ${l}`.trimEnd()), '     */');
            const head = `readonly ${tag}: '${v.name}';`;
            if (v.fields.length === 0) {
                this.line(`    | { ${head} }${end}`);
                return;
            }
            this.line('    | {');
            for (const l of [head, ...v.fields.flatMap((f) => this.property(f))]) this.line(`          ${l}`);
            this.line(`      }${end}`);
        });
    }

    private aggregate(agg: AggregateModel): void {
        const states = agg.states;
        if (agg.kinds.length) this.kindTypes(agg);
        else if (states.length === 0) {
            this.jsdoc([...describedLines(agg), ...invariantLines(agg.invariants), seeLine(agg.location)]);
            this.iface(agg.name, this.fieldSets(agg), [], ownFields(agg));
        } else {
            this.jsdoc([
                `Fields shared by every state of ${agg.label ? `${agg.label} (${agg.name})` : agg.name}.`,
                ...invariantLines(agg.invariants),
                seeLine(agg.location),
            ]);
            this.iface(commonTypeName(agg), this.fieldSets(agg), [], ownFields(agg));
            for (const s of states) {
                this.out.push('');
                this.jsdoc([...describedLines(s), ...invariantLines(s.invariants), seeLine(s.location)]);
                this.iface(stateTypeName(agg, s), [commonTypeName(agg)], [`readonly ${STATE_TAG}: '${s.name}';`], s.fields);
            }
            this.out.push('');
            this.jsdoc([...describedLines(agg), seeLine(agg.location)]);
            this.line(`export type ${agg.name} = ${states.map((s) => stateTypeName(agg, s)).join(' | ')};`);
        }
        this.out.push('');
        this.jsdoc([
            `Restores a trusted ${agg.name} value after caller-side decoding, validation and migration.`,
            'This function does not validate persisted data, invariants or kind–state pairs.',
            seeLine(agg.location),
        ]);
        this.line(`export const restore${agg.name} = (trusted: ${agg.name}): ${agg.name} => trusted;`);
        this.out.push('');
        this.shape(agg);
        this.push(this.checks.aggregate(agg));

        const commands = agg.commands;
        for (const c of commands) {
            this.out.push('');
            if (c.legacy) this.command(agg, c);
            else this.commandNamed(agg, c);
            this.push(c.legacy ? this.requiresCheck(agg, c) : this.checks.namedRequirements(agg, c));
            if (!c.legacy) this.push(this.checks.choices(agg, c));
        }
        if (commands.length > 0) {
            this.out.push('');
            this.jsdoc([
                `Command contracts of ${agg.name}. Implement this interface by hand.`,
                'Commands are pure functions of the aggregate and their parameters: no I/O, no clock, no randomness. IDs and times are passed in as parameters.',
                seeLine(agg.location),
            ]);
            this.line(`export interface ${commandsInterfaceName(agg)} {`);
            for (const c of commands) {
                if (c.label) this.line(`    /** ${oneLine(c.label)} */`);
                this.line(`    readonly ${c.name}: ${commandTypeName(agg, c)};`);
            }
            this.line('}');
        }
        const events = [...new Set(commands.flatMap((c) => (c.legacy ? emittedEvents(c) : emittedEventsInAggregate(agg, c))))];
        if (events.length > 0) {
            this.out.push('');
            this.jsdoc([`Events that the commands of ${agg.name} may emit.`, seeLine(agg.location)]);
            this.line(`export type ${aggregateEventTypeName(agg)} = ${events.map((e) => this.ref(e)).join(' | ')};`);
        }
        this.availability(agg);
    }

    /**
     * Where the commands of an aggregate with states can be called (ADR 0036): the data of the runtime's \`isAvailable\`
     * and \`fromAnyState\`, a guard per command, the error of a command called in another state, and the commands for an
     * aggregate in any state. Factories take no aggregate and have none.
     */
    private availability(agg: AggregateModel): void {
        const commands = agg.states.length || agg.kinds.length ? agg.commands.filter((c) => !c.factory) : [];
        if (!commands.length) return;
        const stateless = !agg.states.length;
        const states = agg.states.map((s) => s.name);
        const hasKinds = agg.kinds.length > 0;
        const kinds = hasKinds ? agg.kinds.map((k) => k.name) : ['*'];
        const valid = (kind: string): readonly string[] => (hasKinds ? validStatesFor(agg, kind) : states);
        /** The source states of a command for a kind, in the order the states are declared (none for a kind without it). */
        const sources = (c: CommandModel, kind: string): string[] => {
            if (!commandKinds(agg, c).includes(kind)) return [];
            const from = c.legacy ? c.transitions.flatMap((t) => t.from) : applicableOutcomes(agg, c, kind).flatMap((o) => o.from);
            return states.filter((s) => from.includes(s) && valid(kind).includes(s));
        };
        /** The type of the aggregate of a kind in a state (`'*'` without kinds; `undefined` without states). */
        const typeOf = (kind: string, state: string | undefined): string =>
            state === undefined ? kindTypeName(agg, kind) : hasKinds ? this.pairType(agg, kind, state) : stateTypeName(agg, state);
        const self = aggregateParamName(agg);
        const lit = (names: readonly string[]): string => names.map((n) => `'${n}'`).join(' | ') || 'never';

        this.out.push('');
        this.jsdoc([
            stateless
                ? `Which kinds have the commands of ${agg.name}.`
                : `Where the commands of ${agg.name} can be called: the source states of each command${hasKinds ? ' per kind (a kind without the command has none)' : ''}.`,
            'Data for `isAvailable`, `availableCommands` and `fromAnyState` of the runtime.',
            seeLine(agg.location),
        ]);
        this.line(`export const ${availabilityName(agg)}: Availability = {`);
        this.line(`    aggregate: ${quote(agg.id)},`);
        if (hasKinds) this.line(`    kindField: ${quote(KIND_TAG)},`);
        if (stateless) this.line('    stateless: true,');
        this.line('    commands: {');
        for (const c of commands) {
            const byKind = commandKinds(agg, c)
                .map((k) => `${quote(k)}: [${sources(c, k).map(quote).join(', ')}]`)
                .join(', ');
            this.line(`        ${c.name}: { ${byKind} },`);
        }
        this.line('    },');
        this.line('};');

        for (const c of commands) {
            const own = commandKinds(agg, c);
            const input = stateless ? own.map((k) => typeOf(k, undefined)) : own.flatMap((k) => sources(c, k).map((s) => typeOf(k, s)));
            const params = c.params.length ? [`${paramsArgName(agg)}: ${paramsTypeName(agg, c)}`] : [];
            const unavailable = stateless
                ? []
                : own.flatMap((k) => {
                      const from = sources(c, k);
                      const others = valid(k).filter((s) => !from.includes(s));
                      // no source state for a kind that has the command: it can never be called on that kind (a caller's bug)
                      if (!from.length || !others.length) return [];
                      const kind = hasKinds ? `, ${quote(k)}` : '';
                      return [`CommandUnavailable<${quote(agg.id)}, ${quote(c.name)}, ${lit(others)}, ${lit(from)}${kind}>`];
                  });
            const without = hasKinds ? kinds.filter((k) => !own.includes(k)) : [];
            const where = stateless
                ? `kind ${own.join(' | ')}`
                : hasKinds
                  ? own.map((k) => `${k}: ${sources(c, k).join(' | ') || 'none'}`).join('; ')
                  : sources(c, '*').join(' | ');
            this.out.push('');
            this.jsdoc([
                `Whether ${agg.name}.${c.name} can be called on the ${self} in its ${stateless ? 'kind' : hasKinds ? 'kind and state' : 'state'} (${where}).`,
                seeLine(c.location),
            ]);
            this.line(
                `export const ${canName(agg, c)} = (${self}: ${agg.name}): ${self} is ${input.join(' | ') || 'never'} => isAvailable(${availabilityName(agg)}, ${quote(c.name)}, ${self});`,
            );
            if (!stateless) {
                this.out.push('');
                this.jsdoc([
                    `The error of ${agg.name}.${c.name} called through \`${anyStateFunctionName(agg)}\` on the ${self} when its state is not one of its source states.`,
                    seeLine(c.location),
                ]);
                this.line(`export type ${unavailableTypeName(agg, c)} = ${unavailable.join(' | ') || 'never'};`);
            }
            if (hasKinds) {
                this.out.push('');
                this.jsdoc([
                    `The error of ${agg.name}.${c.name} called through \`${anyStateFunctionName(agg)}\` on the ${self} of a kind that does not have it${without.length ? ` (${without.join(', ')})` : ''}: it never can be.`,
                    seeLine(c.location),
                ]);
                this.line(
                    `export type ${notForKindTypeName(agg, c)} = ${without.length ? `CommandNotForKind<${quote(agg.id)}, ${quote(c.name)}, ${lit(without)}, ${lit(own)}>` : 'never'};`,
                );
            }
            this.out.push('');
            this.jsdoc([
                hasKinds
                    ? `${agg.name}.${c.name} for the ${self} of any kind${stateless ? '' : ' in any state'}: the command where it can be called (${where})${stateless ? '' : `, \`${unavailableTypeName(agg, c)}\` in another state`}, \`${notForKindTypeName(agg, c)}\` for another kind.`
                    : `${agg.name}.${c.name} for the ${self} in any state: the command in a source state (${where}), and \`${unavailableTypeName(agg, c)}\` in another.`,
                seeLine(c.location),
            ]);
            // a kind that has the command but no source state of it never can have it called (the kind is fixed): not accepted
            const callable = hasKinds ? kinds.filter((k) => !own.includes(k) || stateless || sources(c, k).length) : kinds.filter((k) => sources(c, k).length);
            const subject =
                callable.length === kinds.length
                    ? agg.name
                    : callable.flatMap((k) => (stateless ? [typeOf(k, undefined)] : valid(k).map((s) => typeOf(k, s)))).join(' | ') || 'never';
            const errors = [...(stateless ? [] : [`Err<${unavailableTypeName(agg, c)}>`]), ...(hasKinds ? [`Err<${notForKindTypeName(agg, c)}>`] : [])];
            this.line(`export type ${anyStateTypeName(agg, c)} = (`);
            this.line(`    ${self}: ${subject},`);
            for (const p of params) this.line(`    ${p},`);
            this.line(`) => ReturnType<${commandTypeName(agg, c)}> | ${errors.join(' | ')};`);
        }

        this.out.push('');
        this.jsdoc([
            `The commands of ${agg.name} that take the ${self}, for the ${self} in any state: make it with \`${anyStateFunctionName(agg)}\`.`,
            seeLine(agg.location),
        ]);
        this.line(`export interface ${anyStateInterfaceName(agg)} {`);
        for (const c of commands) {
            if (c.label) this.line(`    /** ${oneLine(c.label)} */`);
            this.line(`    readonly ${c.name}: ${anyStateTypeName(agg, c)};`);
        }
        this.line('}');
        this.out.push('');
        this.jsdoc([
            `The hand-written commands of ${agg.name} for the ${self} in any state: each returns its \`…Unavailable\` error, without calling the command, when the ${self} is not in one of its source states.`,
            seeLine(agg.location),
        ]);
        this.line(
            `export const ${anyStateFunctionName(agg)} = (commands: ${commandsInterfaceName(agg)}): ${anyStateInterfaceName(agg)} => fromAnyState(${availabilityName(agg)}, commands) as ${anyStateInterfaceName(agg)};`,
        );
        this.out.push('');
        this.jsdoc([
            `The commands that can be called on the ${self} in its state, in declaration order (for example, to offer them in a UI).`,
            seeLine(agg.location),
        ]);
        this.line(
            `export const ${availableCommandsName(agg)} = (${self}: ${agg.name}): (keyof ${anyStateInterfaceName(agg)})[] => availableCommands(${availabilityName(agg)}, ${self}) as (keyof ${anyStateInterfaceName(agg)})[];`,
        );
    }

    private pairType(agg: AggregateModel, kind: string, state: string): string {
        return pairTypeName(agg, kind, state);
    }

    /**
     * The types of an aggregate with kinds (ADR 0037): its common fields; per kind (and state), the common fields, the
     * kind's and the state's, tagged with `kind` (and `state`); the union per kind, per state and of all; a guard per kind.
     */
    private kindTypes(agg: AggregateModel): void {
        const states = agg.states;
        const title = agg.label ? `${agg.label} (${agg.name})` : agg.name;
        this.jsdoc([`Fields shared by every kind${states.length ? ' and state' : ''} of ${title}.`, ...invariantLines(agg.invariants), seeLine(agg.location)]);
        this.iface(commonTypeName(agg), this.fieldSets(agg), [], ownFields(agg));
        for (const k of agg.kinds) {
            const kindTag = `readonly ${KIND_TAG}: '${k.name}';`;
            if (!states.length) {
                this.out.push('');
                this.jsdoc([...describedLines(k), ...invariantLines(k.invariants), seeLine(k.location)]);
                this.iface(kindTypeName(agg, k.name), [commonTypeName(agg)], [kindTag], k.fields);
                continue;
            }
            const valid = states.filter((s) => validStatesFor(agg, k.name).includes(s.name));
            for (const s of valid) {
                this.out.push('');
                this.jsdoc([
                    `${k.label ?? k.name} in ${s.label ?? s.name}.`,
                    ...invariantLines(k.invariants),
                    ...invariantLines(s.invariants),
                    seeLine(s.location),
                ]);
                this.iface(
                    this.pairType(agg, k.name, s.name),
                    [commonTypeName(agg)],
                    [`readonly ${STATE_TAG}: '${s.name}';`, kindTag],
                    [...k.fields, ...s.fields],
                );
            }
            this.out.push('');
            this.jsdoc([...describedLines(k), seeLine(k.location)]);
            this.line(`export type ${kindTypeName(agg, k.name)} = ${valid.map((s) => this.pairType(agg, k.name, s.name)).join(' | ') || 'never'};`);
        }
        for (const s of states) {
            const pairs = agg.kinds.filter((k) => validStatesFor(agg, k.name).includes(s.name)).map((k) => this.pairType(agg, k.name, s.name));
            this.out.push('');
            this.jsdoc([...describedLines(s), seeLine(s.location)]);
            this.line(`export type ${stateTypeName(agg, s)} = ${pairs.join(' | ') || 'never'};`);
        }
        this.out.push('');
        this.jsdoc([...describedLines(agg), seeLine(agg.location)]);
        this.line(`export type ${agg.name} = ${agg.kinds.map((k) => kindTypeName(agg, k.name)).join(' | ')};`);
        const self = aggregateParamName(agg);
        for (const k of agg.kinds) {
            this.out.push('');
            this.jsdoc([`Whether the ${self} is of kind ${k.name}${k.label ? ` (${k.label})` : ''}.`, seeLine(k.location)]);
            this.line(
                `export const ${isKindName(agg, k.name)} = (${self}: ${agg.name}): ${self} is ${kindTypeName(agg, k.name)} => ${self}.${KIND_TAG} === '${k.name}';`,
            );
        }
    }

    /** Explicit ADR 0035 outcomes, keyed by their names rather than by target states. */
    private commandNamed(agg: AggregateModel, c: CommandModel): void {
        const self = aggregateParamName(agg);
        const params = c.params.length ? [`${paramsArgName(agg)}: ${paramsTypeName(agg, c)}`] : [];
        const kinds = commandKinds(agg, c);
        const hasKinds = agg.kinds.length > 0;
        const errorNames = [...new Set([...c.errors, ...kinds.flatMap((k) => kindCase(agg, k, c.name)?.requires.map((r) => r.error) ?? [])])];
        const errors = errorNames.length ? errorNames.map((e) => this.ref(e)).join(' | ') : 'never';
        const all = [...new Set(kinds.flatMap((k) => applicableOutcomes(agg, c, k)))];
        const sources = agg.states.length ? agg.states.map((s) => s.name) : [''];
        /** The aggregate of a kind (`'*'` without kinds) in a state (`''` without states). */
        const typeOf = (kind: string, state: string): string =>
            hasKinds
                ? agg.states.length
                    ? this.pairType(agg, kind, state)
                    : kindTypeName(agg, kind)
                : agg.states.length
                  ? stateTypeName(agg, state)
                  : agg.name;
        const inputs = c.factory
            ? []
            : kinds.flatMap((kind) =>
                  sources.flatMap((from) => {
                      const applicable = applicableOutcomes(agg, c, kind).filter((o) => !agg.states.length || o.from.includes(from));
                      if (!applicable.length) return [];
                      return [{ kind, from, applicable, type: typeOf(kind, from) }];
                  }),
              );
        // with kinds (ADR 0037): the inputs grouped by kind, for a contract and a decision keyed by kind
        const byKindInputs = hasKinds ? [...new Set(inputs.map((x) => x.kind))].map((kind) => ({ kind, inputs: inputs.filter((x) => x.kind === kind) })) : [];
        if (c.params.length) {
            this.jsdoc([`The parameters of ${agg.name}.${c.name}, by name.`, seeLine(c.location)]);
            this.line(`export interface ${paramsTypeName(agg, c)} {`);
            for (const l of c.params.flatMap((f) => this.property(f))) this.line(`    ${l}`);
            this.line('}');
            this.out.push('');
        }
        this.jsdoc([
            `${agg.name}.${c.name}${c.factory ? ' — factory' : ''}`,
            ...describedLines(c),
            ...requirementLines(c.requires, (e) => this.ref(e)),
            ...all.map((o) => `@outcome ${o.name}: ${o.from.join(' | ')} -> ${o.to}${o.select ? `; select ${o.select.kind}` : ''}`),
            seeLine(c.location),
        ]);
        if (c.factory) {
            const byName = new Map<string, { outcome: OutcomeModel; kinds: string[] }>();
            for (const kind of kinds)
                for (const o of applicableOutcomes(agg, c, kind)) {
                    const found = byName.get(o.name);
                    if (found) found.kinds.push(kind);
                    else byName.set(o.name, { outcome: o, kinds: [kind] });
                }
            const outcomes = [...byName.values()].map(({ outcome: o, kinds: applicableKinds }): Outcome => ({
                key: o.name,
                first: `aggregate: ${applicableKinds.map((k) => typeOf(k, o.to)).join(' | ')}`,
                emits: [...o.emits],
            }));
            this.line(`export type ${commandTypeName(agg, c)} = (`);
            for (const p of params) this.line(`    ${p},`);
            this.result(') => ', outcomes, errors, '', ';');
        } else if (hasKinds) {
            this.byKind(agg, c, self, params, errors, byKindInputs, false);
        } else {
            const input = inputs.map((x) => x.type).join(' | ') || 'never';
            const resultOf = (x: (typeof inputs)[number]): Outcome[] =>
                x.applicable.map((o): Outcome => ({
                    key: o.name,
                    first: `aggregate: ${typeOf(x.kind, o.to)}`,
                    emits: [...o.emits],
                }));
            if (inputs.length === 1) {
                this.line(`export type ${commandTypeName(agg, c)} = (`);
                this.line(`    ${self}: ${input},`);
                for (const p of params) this.line(`    ${p},`);
                this.result(') => ', resultOf(inputs[0]), errors, '', ';');
            } else {
                this.line(`export type ${commandTypeName(agg, c)} = <S extends ${input}>(`);
                this.line(`    ${self}: S,`);
                for (const p of params) this.line(`    ${p},`);
                this.line(') =>');
                for (const [i, x] of inputs.entries()) {
                    this.line(`    S extends ${x.type} ?`);
                    this.result('        ', resultOf(x), errors, '        ', i === inputs.length - 1 ? ' : never;' : ' :');
                }
                if (!inputs.length) this.line('    never;');
            }
        }
        this.out.push('');
        const keyed = !c.factory && byKindInputs.length > 1;
        this.jsdoc([
            keyed
                ? `Decision of ${agg.name}.${c.name}, one function per kind; each named outcome gives only its set fields and events.`
                : `Decision of ${agg.name}.${c.name}; each named outcome gives only its set fields and events.`,
            c.factory || !agg.states.length
                ? 'Use decideNamed with an outcome-to-target map to form the aggregate.'
                : `Use ${keyed ? 'decideByKind' : 'decideNamed'} with an outcome-to-target map to form the aggregate, and \`{ availability: ${availabilityName(agg)}, command: ${quote(c.name)} }\` to check the ${keyed ? 'kind and the ' : ''}source states.`,
            seeLine(c.location),
        ]);
        if (c.factory) {
            const byName = new Map<string, { outcome: OutcomeModel; kinds: string[] }>();
            for (const kind of kinds)
                for (const o of applicableOutcomes(agg, c, kind)) {
                    const found = byName.get(o.name);
                    if (found) found.kinds.push(kind);
                    else byName.set(o.name, { outcome: o, kinds: [kind] });
                }
            const decisionOutcomes = [...byName.values()].map(({ outcome: o, kinds: applicableKinds }): Outcome => {
                // a factory of a kind names it in `set` (ADR 0037): the runtime makes the aggregate of that kind
                const set = hasKinds
                    ? applicableKinds
                          .map((kind) => `{ readonly ${KIND_TAG}: '${kind}' } & ${this.setType(outcomeFields(agg, c, undefined, o.to, o, kind).set)}`)
                          .join(' | ')
                    : this.setType(outcomeFields(agg, c, undefined, o.to, o).set);
                return { key: o.name, first: `set: ${set}`, emits: [...o.emits] };
            });
            this.line(`export type ${decisionTypeName(agg, c)} = (`);
            for (const p of params) this.line(`    ${p},`);
            this.result(') => ', decisionOutcomes, errors, '', ';');
        } else if (hasKinds) {
            this.byKind(agg, c, self, params, errors, byKindInputs, true);
        } else {
            const input = inputs.map((x) => x.type).join(' | ') || 'never';
            const resultOf = (x: (typeof inputs)[number]): Outcome[] =>
                x.applicable.map((o): Outcome => ({
                    key: o.name,
                    first: `set: ${this.setType(outcomeFields(agg, c, x.from || undefined, o.to, o).set)}`,
                    emits: [...o.emits],
                }));
            if (inputs.length === 1) {
                this.line(`export type ${decisionTypeName(agg, c)} = (`);
                this.line(`    ${self}: ${input},`);
                for (const p of params) this.line(`    ${p},`);
                this.result(') => ', resultOf(inputs[0]), errors, '', ';');
            } else {
                this.line(`export type ${decisionTypeName(agg, c)} = <S extends ${input}>(`);
                this.line(`    ${self}: S,`);
                for (const p of params) this.line(`    ${p},`);
                this.line(') =>');
                for (const [i, x] of inputs.entries()) {
                    this.line(`    S extends ${x.type} ?`);
                    this.result('        ', resultOf(x), errors, '        ', i === inputs.length - 1 ? ' : never;' : ' :');
                }
                if (!inputs.length) this.line('    never;');
            }
        }
    }

    /**
     * The contract (`decision` false) or the decision of a named command of an aggregate with kinds (ADR 0037): for the
     * inputs of one kind, a function of its source states; for several kinds, a function generic over the input whose
     * result is that of its kind (`{ Store: …; Center: … }[S['kind']]`), and a decision with one function per kind
     * (`decideByKind`). Within a kind, the outcomes of its source states are one union.
     */
    private byKind(
        agg: AggregateModel,
        c: CommandModel,
        self: string,
        params: string[],
        errors: string,
        groups: { kind: string; inputs: { kind: string; from: string; applicable: OutcomeModel[]; type: string }[] }[],
        decision: boolean,
    ): void {
        const name = decision ? decisionTypeName(agg, c) : commandTypeName(agg, c);
        const outcomesOf = (g: (typeof groups)[number]): Outcome[] => {
            const byName = new Map<string, { o: OutcomeModel; firsts: Set<string> }>();
            for (const x of g.inputs)
                for (const o of x.applicable) {
                    const first = decision
                        ? this.setType(outcomeFields(agg, c, x.from || undefined, o.to, o, g.kind).set)
                        : agg.states.length
                          ? this.pairType(agg, g.kind, o.to)
                          : kindTypeName(agg, g.kind);
                    const found = byName.get(o.name) ?? { o, firsts: new Set<string>() };
                    found.firsts.add(first);
                    byName.set(o.name, found);
                }
            return [...byName.values()].map(({ o, firsts }) => ({
                key: o.name,
                first: `${decision ? 'set' : 'aggregate'}: ${[...firsts].join(' | ')}`,
                emits: [...o.emits],
            }));
        };
        const inputOf = (g: (typeof groups)[number]): string => g.inputs.map((x) => x.type).join(' | ') || 'never';
        if (groups.length <= 1) {
            const g = groups[0] ?? { kind: '', inputs: [] };
            this.line(`export type ${name} = (`);
            this.line(`    ${self}: ${inputOf(g)},`);
            for (const p of params) this.line(`    ${p},`);
            if (!g.inputs.length) this.line(') => never;');
            else this.result(') => ', outcomesOf(g), errors, '', ';');
            return;
        }
        if (decision) {
            this.line(`export type ${name} = {`);
            for (const g of groups)
                this.result(`    readonly ${g.kind}: (${[`${self}: ${inputOf(g)}`, ...params].join(', ')}) => `, outcomesOf(g), errors, '    ', ';');
            this.line('};');
            return;
        }
        this.line(`export type ${name} = <S extends ${groups.map(inputOf).join(' | ')}>(`);
        this.line(`    ${self}: S,`);
        for (const p of params) this.line(`    ${p},`);
        this.line(') => {');
        for (const g of groups) this.result(`    readonly ${g.kind}: `, outcomesOf(g), errors, '    ', ';');
        this.line(`}[S['${KIND_TAG}']];`);
    }

    /** The fields of an aggregate as data for `decide` (`OrderShape`): the common fields, and each state's own fields. */
    private shape(agg: AggregateModel): void {
        const states = agg.states;
        const list = (fields: readonly FieldModel[]): string => `[${fields.map((f) => `'${f.name}'`).join(', ')}]`;
        this.jsdoc([
            `The fields of ${agg.name} as data for \`decide\`: the common fields${agg.kinds.length ? ', the fields of each kind' : ''}${states.length ? ', and the fields of each state on top of them' : ''}.`,
            seeLine(agg.location),
        ]);
        if (states.length === 0 && !agg.kinds.length) {
            this.line(`export const ${shapeName(agg)}: Shape = { fields: ${list(agg.fields)} };`);
            return;
        }
        this.line(`export const ${shapeName(agg)}: Shape = {`);
        this.line(`    fields: ${list(agg.fields)},`);
        if (agg.kinds.length) this.line(`    kinds: { ${agg.kinds.map((k) => `${k.name}: ${list(k.fields)}`).join(', ')} },`);
        if (states.length) this.line(`    states: { ${states.map((s) => `${s.name}: ${list(s.fields)}`).join(', ')} },`);
        this.line('};');
    }

    private command(agg: AggregateModel, c: CommandModel): void {
        const stateful = agg.states.length > 0;
        // without states, an aggregate with kinds (ADR 0037): a kind's command takes and makes the aggregate of its kind
        const whole = c.kind ? kindTypeName(agg, c.kind) : agg.name;
        const stateUnion = (names: readonly string[]): string =>
            stateful
                ? unique(names)
                      .map((n) => stateTypeName(agg, n))
                      .join(' | ')
                : whole;
        const transitions = stateful ? c.transitions : [];
        // TODO(step 3): use outcomesOfCommand from contexts/modeling/src/domain/model.ts.
        // One output for every input (as `A | B -> C`): a plain function. Outputs that depend on the input
        // (`A -> A, B -> B`, or `emits X when A ->`): a function generic over the input state, whose result is that of
        // its state, looked up in an object keyed by the source states.
        const generic = stateful && outputsVary(c.factory, transitions, c.emits);
        const input = stateUnion(transitions.flatMap((t) => t.from));
        const self = aggregateParamName(agg);
        // the parameters as one object (`params: CancelOrderParams`), and none without parameters
        const params = c.params.length ? [`${paramsArgName(agg)}: ${paramsTypeName(agg, c)}`] : [];
        const errors = c.errors.length === 0 ? 'never' : c.errors.map((e) => this.ref(e)).join(' | ');
        // the outcomes of an input state (`undefined`: a factory, or no states): one per target, keyed by its name; the
        // contract holds the aggregate, the decision what to `set`
        const outcomes = (from: string | undefined, targets: readonly string[], decision: boolean): Outcome[] =>
            (stateful ? unique(targets) : [undefined]).map((to) => ({
                key: to ?? agg.name,
                first: decision
                    ? `set: ${c.factory && c.kind ? `{ readonly ${KIND_TAG}: '${c.kind}' } & ` : ''}${this.setType(outcomeFields(agg, c, from, to).set)}`
                    : `aggregate: ${to ? stateTypeName(agg, to) : whole}`,
                emits: c.emits.filter((e) => emitApplies(e, from, to)),
            }));
        const requires = requirementLines(c.requires, (e) => this.ref(e));
        const changes = c.factory
            ? []
            : [`@changes ${c.changes.length ? c.changes.join(', ') : `none — the command changes no ${stateful ? 'common ' : ''}field`}`];
        const sources = transitions.flatMap((t) => t.from.map((from) => ({ from, to: t.to })));

        const transition = c.factory
            ? `new -> ${transitions[0]?.to.join(' | ') || agg.name}`
            : transitions.map((t) => `${t.from.join(' | ')} -> ${t.to.join(' | ')}`).join('; ');
        if (c.params.length) {
            this.jsdoc([`The parameters of ${agg.name}.${c.name}, by name.`, seeLine(c.location)]);
            this.line(`export interface ${paramsTypeName(agg, c)} {`);
            for (const l of c.params.flatMap((f) => this.property(f))) this.line(`    ${l}`);
            this.line('}');
            this.out.push('');
        }
        this.jsdoc([
            `${agg.name}.${c.name}${transition ? ` (${transition})` : ''}${c.factory ? ' — factory' : ''}`,
            ...describedLines(c),
            ...requires,
            ...changes,
            ...this.emitsLines(c.emits.map((e) => ({ e, when: e.when }))),
            seeLine(c.location),
        ]);
        this.line(`export type ${commandTypeName(agg, c)} = ${generic ? `<S extends ${input}>` : ''}(`);
        for (const p of [...(c.factory ? [] : [`${self}: ${generic ? 'S' : input}`]), ...params]) this.line(`    ${p},`);
        const first = transitions[0];
        if (!generic) {
            this.result(') => ', outcomes(c.factory ? undefined : first?.from[0], first?.to ?? [], false), errors, '', ';');
        } else {
            this.line(') => {');
            for (const { from, to } of sources) {
                this.memberDoc(this.emitsLines(this.emitsFrom(c, from, to)));
                this.result(`    readonly ${from}: `, outcomes(from, to, false), errors, '    ', ';');
            }
            this.line(`}[S['${STATE_TAG}']];`);
        }

        // The decision: one handler per source state, or one function for a factory and without states.
        const keyed = stateful && !c.factory;
        const outcomeLines = keyed
            ? sources.flatMap(({ from, to }) => unique(to).map((t) => this.outcomeLine(agg, c, from, t)))
            : (stateful ? unique(first?.to ?? []) : [undefined]).map((t) => this.outcomeLine(agg, c, undefined, t));
        this.out.push('');
        this.jsdoc([
            `${agg.name}.${c.name}, decided ${keyed ? 'per source state' : 'by one function'}; implement it with \`decide(${shapeName(agg)}, …)\` from the runtime.`,
            `Each outcome gives the fields of \`set\`, and \`decide\` makes the aggregate${c.factory ? ' from them' : ', taking the other fields from the input'}.`,
            ...requires,
            ...changes,
            ...outcomeLines,
            ...(keyed ? [] : this.emitsLines(c.emits.map((e) => ({ e, when: e.when })))),
            seeLine(c.location),
        ]);
        if (!keyed) {
            this.line(`export type ${decisionTypeName(agg, c)} = (`);
            for (const p of [...(c.factory ? [] : [`${self}: ${input}`]), ...params]) this.line(`    ${p},`);
            this.result(') => ', outcomes(undefined, first?.to ?? [], true), errors, '', ';');
            return;
        }
        this.line(`export type ${decisionTypeName(agg, c)} = {`);
        for (const { from, to } of sources) {
            this.memberDoc(this.emitsLines(this.emitsFrom(c, from, to)));
            this.result(
                `    readonly ${from}: (${[`${self}: ${stateTypeName(agg, from)}`, ...params].join(', ')}) => `,
                outcomes(from, to, true),
                errors,
                '    ',
                ';',
            );
        }
        this.line('};');
    }

    /** The generated check of a command's requirements, with the parameters of its contract. */
    private requiresCheck(agg: AggregateModel, c: CommandModel): string[] {
        const states = agg.states;
        const sources = unique(
            c.legacy ? c.transitions.flatMap((t) => t.from) : commandKinds(agg, c).flatMap((k) => applicableOutcomes(agg, c, k).flatMap((o) => o.from)),
        );
        const input = states.length ? sources.map((n) => stateTypeName(agg, n)).join(' | ') || 'never' : c.kind ? kindTypeName(agg, c.kind) : agg.name;
        const subject = c.factory ? undefined : { name: aggregateParamName(agg), type: input };
        const params = c.params.length ? { name: paramsArgName(agg), type: paramsTypeName(agg, c) } : undefined;
        return this.checks.requires(agg, c, commandTypeName(agg, c), subject, params);
    }

    /** The entries of `emits` for a source state, with `when` reduced to what still selects among its targets. */
    private emitsFrom(c: CommandModel, from: string, targets: readonly string[]): { e: EmitModel; when?: OutcomePatternModel }[] {
        return c.emits
            .filter((e) => targets.some((to) => emitApplies(e, from, to)))
            .map((e) => ({ e, when: e.when?.to.length && !targets.every((to) => e.when!.to.includes(to)) ? { from: [], to: e.when.to } : undefined }));
    }

    /** What the decision gives for an outcome, and what `decide` carries over and drops, in words. */
    private outcomeLine(agg: AggregateModel, c: CommandModel, from: string | undefined, to: string | undefined): string {
        const head = c.factory ? `new -> ${to ?? agg.name}` : to ? `${from} -> ${to}` : agg.name;
        if (c.factory) return `${head} — set: every field`;
        const { set, carried, dropped } = outcomeFields(agg, c, from, to);
        const names = (fields: FieldModel[]): string => fields.map((f) => f.name).join(', ');
        const fresh = (f: FieldModel): boolean => !agg.fields.includes(f) && !carried.includes(f) && !c.changes.includes(f.name);
        return [
            `${head} — set: ${set.length ? set.map((f) => `${f.name}${fresh(f) ? ` (new in ${to})` : ''}`).join(', ') : 'nothing'}`,
            ...(carried.length ? [`carried over: ${names(carried)}`] : []),
            ...(dropped.length ? [`dropped: ${names(dropped)}`] : []),
        ].join('; ');
    }

    /** The type of the `set` of an outcome: every field required, an optional one cleared with `undefined`. */
    private setType(fields: FieldModel[]): string {
        if (fields.length === 0) return NO_CHANGES_TYPE;
        return `{ ${fields.map((f) => `readonly ${f.name}: ${this.fieldType(f)}${f.cardinality === 'optional' ? ' | undefined' : ''}`).join('; ')} }`;
    }

    /** A JSDoc block for a member of a type (single line when short). */
    private memberDoc(lines: string[]): void {
        const doc = lines.flatMap((l) => comment(l).split('\n'));
        if (doc.length === 1) this.line(`    /** ${doc[0]} */`);
        else if (doc.length > 1) this.out.push('    /**', ...doc.map((l) => `     * ${l}`), '     */');
    }

    /**
     * `Result<…>` of a command or a decision, starting with `head` on the current line: the success value is keyed by
     * the outcome's state (`{ readonly Confirmed: { aggregate, events } }`, or `{ set, events }` in a decision); with
     * several outcomes, a union whose branches mark the other keys `?: never`, so that a value holds exactly one outcome.
     */
    private result(head: string, outcomes: Outcome[], errors: string, indent: string, end: string): void {
        const body = (o: Outcome, pad: string): string[] => [
            `${pad}readonly ${o.key}: {`,
            `${pad}    readonly ${o.first};`,
            `${pad}    readonly events: ${this.events(o.emits)};`,
            `${pad}};`,
        ];
        if (outcomes.length === 1) {
            this.line(`${head}Result<{`);
            for (const l of body(outcomes[0], `${indent}    `)) this.line(l);
            this.line(`${indent}}, ${errors}>${end}`);
            return;
        }
        this.line(`${head}Result<`);
        outcomes.forEach((o, i) => {
            this.line(`${indent}    | {`);
            for (const l of body(o, `${indent}          `)) this.line(l);
            for (const other of outcomes) if (other !== o) this.line(`${indent}          readonly ${other.key}?: never;`);
            this.line(`${indent}      }${i === outcomes.length - 1 ? ',' : ''}`);
        });
        this.line(`${indent}    ${errors}`);
        this.line(`${indent}>${end}`);
    }

    /** The `events` of an outcome: one property per event, keyed by its qualified name, typed by its multiplicity. */
    private events(emits: EmitModel[]): string {
        if (emits.length === 0) return NO_EVENTS_TYPE;
        const props = emits.map((e) => {
            const t = this.ref(e.event);
            const key = `'${e.event}'`;
            if (e.lower === 1 && e.upper === 1) return `readonly ${key}: ${t}`;
            if (e.lower === 0 && e.upper === 1) return `readonly ${key}?: ${t}`;
            if (e.lower === 1 && e.upper === undefined) return `readonly ${key}: readonly [${t}, ...${t}[]]`;
            if (e.lower === 0 && e.upper === undefined) return `readonly ${key}: readonly ${t}[]`;
            return `/** ${times(e).words} */ readonly ${key}: readonly ${t}[]`;
        });
        return `{ ${props.join('; ')} }`;
    }

    /** `@emits` lines: what each entry means, in words. `when` is the condition to state (absent: on every success). */
    private emitsLines(entries: { e: EmitModel; when?: OutcomePatternModel }[]): string[] {
        if (entries.length === 0) return ['@emits nothing'];
        return entries.map(({ e, when }) => {
            const { words, unchecked } = times(e);
            return `@emits ${this.ref(e.event)}${e.multiplicity} — ${words} ${condition(when)}${unchecked ? ' (not checked by the types)' : ''}`;
        });
    }

    private iface(name: string, bases: readonly string[], extra: readonly string[], fields: readonly FieldModel[]): void {
        const lines = [...extra, ...fields.flatMap((f) => this.property(f))];
        const ext = bases.length ? ` extends ${bases.join(', ')}` : '';
        if (lines.length === 0) {
            this.line(`export interface ${name}${ext} {}`);
            return;
        }
        this.line(`export interface ${name}${ext} {`);
        for (const l of lines) this.line(`    ${l}`);
        this.line('}');
    }

    private property(f: FieldModel): string[] {
        const doc = [f.label, f.doc].filter(Boolean).join(' — ');
        // The target of `references`, linked by the name this module uses for it (a link to another context imports its
        // types), so that hover and go-to-definition reach it.
        const see = f.kind === 'references' && f.target ? `@see {@link ${this.link(f.target)}}` : '';
        const lines = [...(doc ? [oneLine(doc)] : []), ...(see ? [see] : [])];
        const prefix = lines.length > 1 ? ['/**', ...lines.map((l) => ` * ${l}`), ' */'] : lines.map((l) => `/** ${l} */`);
        if (f.cardinality === 'optional') return [...prefix, `readonly ${f.name}?: ${this.fieldType(f)};`];
        return [...prefix, `readonly ${f.name}: ${this.fieldType(f)};`];
    }

    private fieldType(f: FieldModel): string {
        const t = this.typeExpr(f.type);
        switch (f.cardinality) {
            case 'many':
                return `readonly ${t}[]`;
            case 'nonEmpty':
                return `readonly [${t}, ...${t}[]]`;
            default:
                return t;
        }
    }

    private typeExpr(t: TypeExpr): string {
        return t.kind === 'primitive' ? PRIMITIVES[t.name] : this.ref(t.ref);
    }

    /** TypeScript reference to a qualified element name, importing other contexts as namespaces. */
    private ref(qname: string): string {
        const dot = qname.indexOf('.');
        const ctx = qname.slice(0, dot);
        const name = qname.slice(dot + 1);
        if (ctx === this.ctx) return name;
        this.imports.add(ctx);
        return `${ctx}.${name}`;
    }

    /** The name of a qualified element in a `{@link}`, as {@link ContextEmitter.ref} names it, importing other contexts for the link only. */
    private link(qname: string): string {
        const dot = qname.indexOf('.');
        const ctx = qname.slice(0, dot);
        if (ctx === this.ctx) return qname.slice(dot + 1);
        this.linked.add(ctx);
        return qname;
    }

    /** Emits a JSDoc block (single line when short); nothing for an empty list. */
    private jsdoc(lines: string[]): void {
        const all = lines.flatMap((l) => comment(l).split('\n'));
        if (all.length === 0) return;
        if (all.length === 1) this.out.push(`/** ${all[0]} */`);
        else this.out.push('/**', ...all.map((l) => ` * ${l}`.trimEnd()), ' */');
    }

    private line(text: string): void {
        this.out.push(text);
    }
}
